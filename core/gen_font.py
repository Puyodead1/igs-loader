#!/usr/bin/env python3
"""gen_font.py OUT.h - render ASCII 32..126 from DejaVu Sans Mono Bold into a
1-bit bitmap font for glBitmap (rows bottom-up, MSB first)."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
SIZE = 22
W, H = 14, 26                 # cell; advance is W
font = ImageFont.truetype(FONT, SIZE)
ascent, _ = font.getmetrics()
rows = []
for c in range(32, 127):
    img = Image.new('1', (W, H), 0)
    ImageDraw.Draw(img).text((0, H - 4 - ascent), chr(c), font=font, fill=1)
    px = img.load()
    glyph = []
    for y in range(H - 1, -1, -1):          # bottom-up for glBitmap
        bits = 0
        for x in range(16):
            bits = (bits << 1) | (1 if x < W and px[x, y] else 0)
        glyph += [bits >> 8, bits & 0xff]
    rows.append(glyph)
with open(sys.argv[1], 'w') as f:
    f.write('/* generated by gen_font.py from DejaVu Sans Mono Bold %d */\n' % SIZE)
    f.write('#define FONT_W %d\n#define FONT_H %d\n' % (W, H))
    f.write('static const unsigned char font_bits[95][%d] = {\n' % (2 * H))
    for g in rows:
        f.write('    {' + ','.join('0x%02x' % b for b in g) + '},\n')
    f.write('};\n')
